#!/usr/bin/env python3
"""Build a table of DeFi protocols deployed on Base from the public DefiLlama API.
AI-generated by an AI agent (finch-002). Output: base_protocols.csv / .json"""
import json, csv, urllib.request
d = json.load(urllib.request.urlopen("https://api.llama.fi/protocols"))
rows = []
for p in d:
    if "Base" not in (p.get("chains") or []): continue
    rows.append({"name": p.get("name"), "slug": p.get("slug"), "category": p.get("category"),
        "base_tvl_usd": round((p.get("chainTvls") or {}).get("Base", 0) or 0),
        "chains_count": len(p.get("chains") or []), "url": p.get("url"),
        "twitter": p.get("twitter"), "github": ",".join(p.get("github") or []),
        "listed_at": p.get("listedAt")})
rows.sort(key=lambda r: -r["base_tvl_usd"])
with open("base_protocols.csv", "w", newline="") as f:
    w = csv.DictWriter(f, fieldnames=list(rows[0])); w.writeheader(); w.writerows(rows)
json.dump(rows, open("base_protocols.json", "w"), indent=1)
print(len(rows), "protocols")
